"""Managed agent plugin — per-system-prompt agent definitions for ``--agent``.

agy has no ``--system-prompt`` flag (verified against 1.1.4), but it DOES
support custom agents: any plugin directory under
``~/.gemini/config/plugins/<name>/`` containing ``plugin.json`` and
``agents/*.md`` files (Claude-style frontmatter + body) defines agents that

* are discovered at conversation start — files can be added/removed on disk
  with no install or reinstall step (verified live),
* are selectable per spawn with ``--agent <name>``,
* have their ``.md`` body honored as the persona/system prompt, effectively
  replacing the CLI's built-in "Antigravity Senior Systems Architect" identity,
* stay in effect across ``--conversation <id>`` resumes,
* honor the frontmatter ``tools:`` list as an **allowlist** of builtins
  (verified against 1.1.27: ``["view_file"]`` → only view_file (+ manage_task)
  is offered to the model; ``[]`` → none). ``call_mcp_tool`` cannot be named
  explicitly (the agent fails to start) — it is only granted by ``"*"``.

This is a tool allowlist, NOT an OS/filesystem sandbox: a plain-chat request whose
content is untrusted (a web page hermes asks to summarize) is answered by an
agent that can, at most, read files — never run a shell.

This manager owns ONE such plugin directory (default
``~/.gemini/config/plugins/hermes-bridge``) and materializes each
(system prompt, tools mode) pair into ``agents/hermes-<sha1[:12]>.md`` on
demand. Slugs are deterministic, so repeated requests, conversation-cache
resumes, and tool-loop turns all reuse the same file. Pruning only ever removes
files matching our own slug pattern; foreign files are never touched.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import os
import re
import tempfile
from pathlib import Path
from typing import Optional

logger = logging.getLogger("agi.agentcfg")

_SLUG_RE = re.compile(r"^hermes-[0-9a-f]{12}\.md$")

_PLUGIN_JSON = {
    "name": "hermes-bridge",
    "version": "0.2.0",
    "description": "Per-request system-prompt agents managed by antigravity-interface.",
    "author": {"name": "antigravity-interface"},
}

# tools-mode name → frontmatter `tools:` value. See Settings.plain_chat_tools.
TOOLS_BY_MODE: dict[str, str] = {
    "all": '"*"',
    "readonly": '["view_file"]',
    "none": "[]",
}

# Body used when a request carries no system message but we still need an
# agent to carry the tools allowlist. Neutral: does not fight the client's
# own instructions in the user turn.
NEUTRAL_SYSTEM_PROMPT = "You are a helpful assistant."


def default_plugin_path() -> Path:
    return Path("~/.gemini/config/plugins/hermes-bridge").expanduser()


def slug_for(system_prompt: str, tools_mode: str = "all") -> str:
    # The mode is part of the identity: the same prompt with a different tool
    # allowlist must be a different agent file.
    key = system_prompt if tools_mode == "all" else f"{tools_mode}\x00{system_prompt}"
    return "hermes-" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:12]


def _agent_md(slug: str, system_prompt: str, tools_mode: str) -> str:
    tools = TOOLS_BY_MODE[tools_mode]
    return (
        "---\n"
        f"name: {slug}\n"
        f"description: System-prompt agent generated by antigravity-interface (tools={tools_mode}).\n"
        f"tools: {tools}\n"
        "---\n"
        "\n"
        f"{system_prompt}\n"
    )


class AgentPluginManager:
    """Owns the managed plugin directory and its generated agent files."""

    def __init__(self, path: Optional[Path] = None, max_agents: int = 64) -> None:
        self.path = (Path(path).expanduser() if path else default_plugin_path())
        self.max_agents = max_agents
        self._lock = asyncio.Lock()

    @property
    def agents_dir(self) -> Path:
        return self.path / "agents"

    # ── public API ───────────────────────────────────────────────────────────

    async def ensure_agent(
        self, system_prompt: Optional[str], tools_mode: str = "all"
    ) -> Optional[str]:
        """Materialize ``system_prompt`` (with the ``tools_mode`` allowlist) as
        an agent definition; return its slug.

        ``system_prompt=None`` uses a neutral body — the agent then exists only
        to carry the tools allowlist. Returns ``None`` (caller falls back to
        prompt-preamble injection with agy's default tool set) when the plugin
        directory cannot be written — never raises.
        """
        if tools_mode not in TOOLS_BY_MODE:
            raise ValueError(f"unknown tools mode {tools_mode!r}")
        body = system_prompt if system_prompt else NEUTRAL_SYSTEM_PROMPT
        slug = slug_for(body, tools_mode)
        async with self._lock:
            try:
                self._ensure_plugin()
                target = self.agents_dir / f"{slug}.md"
                content = _agent_md(slug, body, tools_mode)
                if target.exists() and target.read_text(encoding="utf-8") == content:
                    # Bump mtime so LRU pruning sees this agent as in use.
                    os.utime(target)
                else:
                    # Missing, or written by an older template — (re)write.
                    self._write_atomic(target, content)
                    logger.info("agent-plugin: wrote %s (tools=%s)", target.name, tools_mode)
                self._prune()
            except OSError:
                logger.warning(
                    "agent-plugin: cannot manage %s — falling back to prompt injection",
                    self.path, exc_info=True,
                )
                return None
        return slug

    # ── internals ────────────────────────────────────────────────────────────

    def _ensure_plugin(self) -> None:
        self.agents_dir.mkdir(parents=True, exist_ok=True)
        manifest = self.path / "plugin.json"
        if not manifest.exists():
            self._write_atomic(manifest, json.dumps(_PLUGIN_JSON, indent=2) + "\n")
            logger.info("agent-plugin: created %s", self.path)

    def _write_atomic(self, target: Path, content: str) -> None:
        fd, tmp = tempfile.mkstemp(dir=str(target.parent), suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            os.replace(tmp, str(target))
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise

    def _prune(self) -> None:
        """Drop the oldest generated agents beyond ``max_agents`` (ours only)."""
        owned = [p for p in self.agents_dir.iterdir() if _SLUG_RE.match(p.name)]
        if len(owned) <= self.max_agents:
            return
        owned.sort(key=lambda p: p.stat().st_mtime)
        for victim in owned[: len(owned) - self.max_agents]:
            try:
                victim.unlink()
                logger.info("agent-plugin: pruned %s", victim.name)
            except OSError:
                pass
